def get_prompt(key, default=''):
    """저장된 프롬프트가 있으면 그것을, 없으면 코드 기본값을 준다."""
    from .models import SystemSetting

    row = SystemSetting.objects.filter(key=key).first()
    if row and row.value.strip():
        return row.value
    return default
